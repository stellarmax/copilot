import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { Check, ChevronRight, CircleAlert, RefreshCw, X } from "lucide-react";
import { getClaim, verifyClaim } from "../lib/api";
import { ErrorState, LoadingState } from "./Feedback";

interface TraceDrawerProps {
  claimId: string | null;
  onClose: () => void;
}

function pretty(value: unknown) {
  return JSON.stringify(value, null, 2);
}

export function TraceDrawer({ claimId, onClose }: TraceDrawerProps) {
  const queryClient = useQueryClient();
  const trace = useQuery({
    queryKey: ["claim", claimId],
    queryFn: () => getClaim(claimId!),
    enabled: Boolean(claimId),
  });
  const verify = useMutation({
    mutationFn: () => verifyClaim(claimId!),
    onSuccess: (result) => queryClient.setQueryData(["claim", claimId], result),
  });

  if (!claimId) return null;
  const data = verify.data ?? trace.data;

  return (
    <div className="drawer-scrim" onMouseDown={(event) => event.target === event.currentTarget && onClose()}>
      <aside className="trace-drawer" aria-label="Claim evidence" aria-modal="true" role="dialog">
        <div className="drawer-head">
          <div>
            <span className="eyebrow">EVIDENCE RECORD</span>
            <h2>Claim trace</h2>
          </div>
          <button className="icon-button" onClick={onClose} aria-label="Close evidence panel">
            <X size={18} />
          </button>
        </div>
        <div className="drawer-content">
          {trace.isLoading && <LoadingState label="Loading evidence" />}
          {trace.error && <ErrorState message={trace.error.message} />}
          {data && (
            <>
              <section className="trace-conclusion">
                <div className="trace-status"><Check size={14} /> {data.status}</div>
                <p>{data.claim_text}</p>
                <code>{data.claim_id}</code>
              </section>
              <section className="trace-section">
                <div className="section-heading"><h3>Provenance</h3><span>{data.rule_version}</span></div>
                <dl className="meta-list">
                  <div><dt>Generated by</dt><dd>{data.generated_by}</dd></div>
                  <div><dt>Business date</dt><dd>{data.as_of_date}</dd></div>
                  <div><dt>Generated at</dt><dd>{new Date(data.generated_at).toLocaleString()}</dd></div>
                </dl>
              </section>
              <section className="trace-section">
                <div className="section-heading"><h3>Source snapshots</h3><span>{data.source_refs.length} files</span></div>
                {data.source_refs.map((source, index) => (
                  <div className="source-row" key={`${String(source.file)}-${index}`}>
                    <span>{String(source.file ?? source.table ?? "Source file")}</span>
                    <code>{String(source.snapshot_version ?? "Snapshot unavailable").slice(0, 14)}</code>
                  </div>
                ))}
                {data.source_rows.length > 0 && <p className="muted-note">{data.source_rows.length} supporting source rows stored in the trace.</p>}
              </section>
              <section className="trace-section">
                <div className="section-heading"><h3>Calculation steps</h3><span>{data.calculation_steps.length} steps</span></div>
                <ol className="step-list">
                  {data.calculation_steps.map((step, index) => (
                    <li key={`${String(step.step_name)}-${index}`}>
                      <span className="step-index">{String(index + 1).padStart(2, "0")}</span>
                      <div><strong>{String(step.step_name ?? "Calculation")}</strong><p>{String(step.formula ?? "Deterministic tool calculation")}</p><pre>{pretty(step.output)}</pre></div>
                      {index < data.calculation_steps.length - 1 && <ChevronRight className="step-chevron" size={15} />}
                    </li>
                  ))}
                </ol>
              </section>
              {data.verification && (
                <section className={`verification-result ${data.verification.result === "CONSISTENT" ? "is-good" : "is-alert"}`}>
                  {data.verification.result === "CONSISTENT" ? <Check size={17} /> : <CircleAlert size={17} />}
                  <div><strong>{data.verification.result}</strong><p>{data.verification.likely_cause ?? "The current result matches the stored claim."}</p></div>
                </section>
              )}
            </>
          )}
        </div>
        <div className="drawer-foot">
          <button className="button button-secondary" onClick={() => verify.mutate()} disabled={verify.isPending || trace.isLoading}>
            <RefreshCw size={15} className={verify.isPending ? "spin" : ""} />
            {verify.isPending ? "Verifying" : "Re-verify claim"}
          </button>
        </div>
      </aside>
    </div>
  );
}